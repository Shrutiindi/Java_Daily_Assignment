package DailyAssignment;

public class Day4 {

	public static void main(String[] args) {
        byte userAge = 25;
        short postalCode = 5600;
        int annualSalary = 85000;
        long globalPopulation = 8000000000L;
        float itemPrice = 19.99f;
        double precisePi = 3.141592653589793;
        char gradeLetter = 'A';
        boolean isJavaFun = true;
        String standardMessage = "Welcome to Java Programming!";

    

        System.out.println("--- Primitive Data Types ---");
        System.out.println("byte value    : " + userAge);
        System.out.println("short value   : " + postalCode);
        System.out.println("int value     : " + annualSalary);
        System.out.println("long value    : " + globalPopulation);
        System.out.println("float value   : " + itemPrice);
        System.out.println("double value  : " + precisePi);
        System.out.println("char value    : " + gradeLetter);
        System.out.println("boolean value : " + isJavaFun);

        System.out.println("\n--- Non-Primitive Data Types ---");
        System.out.println("String value  : " + standardMessage);
       
	}

}
